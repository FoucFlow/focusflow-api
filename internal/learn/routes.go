package learn

import (
	"focusflow-api/internal/auth"

	"github.com/gin-gonic/gin"
)

// Routes registers the course builder and learner flow under /api/learn.
// Every route needs a signed-in user; creator-only checks happen per handler.
func (h *Handler) Routes(r *gin.Engine) {
	// Direct file upload from the browser: signed token instead of a session
	up := r.Group("/api/learn/upload", h.uploadCORS())
	up.OPTIONS("/:id", func(*gin.Context) {})
	up.POST("/:id", h.DirectUpload)

	g := r.Group("/api/learn", auth.AuthMiddleware())
	r.GET("/api/certificates/:code", h.VerifyCertificate) // public check
	g.GET("/quiz-template.csv", func(c *gin.Context) {
		c.Header("Content-Disposition", `attachment; filename="focusflow-quiz-template.csv"`)
		c.Data(200, "text/csv; charset=utf-8", []byte(CSVTemplate))
	})

	// Admin: AI usage against provider quotas
	r.GET("/api/admin/ai/quota", auth.AuthMiddleware(), auth.RequireRole(auth.RoleAdmin), h.AIQuota)
	r.GET("/api/admin/institutions", auth.AuthMiddleware(), auth.RequireRole(auth.RoleAdmin), h.AdminInstitutions)
	r.PUT("/api/admin/institutions/:iid/plan", auth.AuthMiddleware(), auth.RequireRole(auth.RoleAdmin), h.AdminInstitutionPlan)

	g.GET("/me", h.Me)
	g.GET("/browse", h.Browse)
	g.GET("/categories", h.Categories)

	g.GET("/courses/:id", h.GetCourse)
	g.POST("/courses/:id/join", h.Join)
	g.GET("/courses/:id/materials", h.ListMaterials)
	g.POST("/courses/:id/materials", h.AddMaterial)
	g.POST("/courses/:id/upload-url", h.UploadURL)
	g.POST("/courses/:id/organise", h.Organise)
	g.POST("/courses/:id/references", h.FindReferences)
	g.POST("/courses/:id/units", h.AddUnit)
	g.PUT("/courses/:id/units/order", h.ReorderUnits)
	g.POST("/courses/:id/publish", h.Publish)
	g.POST("/courses/:id/unpublish", h.Unpublish)

	g.PUT("/courses/:id/materials/order", h.ReorderMaterials)
	g.PUT("/materials/:mid", h.RenameMaterial)
	g.DELETE("/materials/:mid", h.DeleteMaterial)
	g.POST("/materials/:mid/retry", h.RetryMaterial)
	g.GET("/materials/:mid/pages", h.SlidePages)
	g.PUT("/slide-pages/:pid", h.UpdateSlidePage)
	g.POST("/materials/:mid/suggest-units", h.SuggestUnits)
	g.GET("/materials/:mid/file", h.MaterialFile)
	g.GET("/materials/:mid/page-count", h.PDFPageCount)
	g.GET("/courses/:id/invite", h.GetInvite)
	g.PUT("/courses/:id/invite", h.UpdateInvite)
	g.GET("/invites/:code", h.InviteInfo)
	g.POST("/invites/:code/join", h.JoinByInvite)
	g.GET("/courses/:id/learners", h.CourseLearners)
	g.DELETE("/courses/:id/learners/:uid", h.RemoveLearner)
	// institutions (M4)
	g.POST("/institutions", h.CreateInstitution)
	g.GET("/institutions", h.MyInstitutions)
	g.GET("/institutions/:iid", h.GetInstitution)
	g.PUT("/institutions/:iid", h.UpdateInstitution)
	g.POST("/institutions/:iid/members", h.AddMember)
	g.PUT("/institutions/:iid/members/:mid", h.UpdateMember)
	g.DELETE("/institutions/:iid/members/:mid", h.RemoveMember)
	g.DELETE("/institutions/:iid/membership", h.LeaveInstitution)
	g.POST("/institutions/:iid/courses/:cid/results-access", h.ApproveResults)
	g.GET("/courses/:id/class", h.GetClass)
	g.PUT("/courses/:id/class", h.UpdateClass)
	g.POST("/courses/:id/roster", h.ImportRoster)
	g.DELETE("/courses/:id/roster/:rid", h.RemoveRosterEntry)
	g.POST("/courses/:id/roster/invite", h.InviteRoster)
	g.GET("/courses/:id/consent", h.GetConsent)
	g.POST("/courses/:id/consent", h.SetConsent)
	g.DELETE("/courses/:id/consent", h.SetConsent)
	g.GET("/courses/:id/results", h.ClassResults)
	g.GET("/courses/:id/results/:uid/help", h.HelpDraft)
	g.POST("/courses/:id/results/:uid/help", h.SendHelp)
	g.PUT("/courses/:id/build-mode", h.SetBuildMode)
	g.PUT("/courses/:id/slide-units", h.SaveSlideUnits)
	g.GET("/units/:uid/pages", h.UnitPages)
	g.POST("/courses/:id/quizzes", h.CreateQuiz)
	g.PUT("/units/:uid/quiz", h.UpdateQuiz)
	g.POST("/units/:uid/questions/import", h.ImportQuestions)
	g.POST("/attempts/:aid/check", h.CheckAnswer)
	g.POST("/attempts/:aid/explain", h.ExplainAnswers)
	g.POST("/attempts/:aid/snapshots", h.AddSnapshot)
	g.GET("/attempts/:aid/snapshots/:n", h.GetSnapshot)

	g.GET("/units/:uid", h.GetUnit)
	g.PUT("/units/:uid", h.UpdateUnit)
	g.DELETE("/units/:uid", h.DeleteUnit)
	g.POST("/units/:uid/complete", h.CompleteUnit)
	g.POST("/units/:uid/concepts", h.AddConcept)
	g.PUT("/units/:uid/concepts/order", h.ReorderConcepts)
	g.PUT("/concepts/:cid", h.UpdateConcept)
	g.DELETE("/concepts/:cid", h.DeleteConcept)

	// Unit tests (FEATURES.md step 3)
	g.GET("/units/:uid/test", h.GetTest)
	g.PUT("/units/:uid/test", h.UpdateTest)
	g.POST("/units/:uid/test/start", h.StartTest)
	g.POST("/units/:uid/questions", h.AddQuestion)
	g.POST("/units/:uid/questions/generate", h.GenerateQuestions)
	g.PUT("/questions/:qid", h.UpdateQuestion)
	g.DELETE("/questions/:qid", h.DeleteQuestion)
	g.GET("/courses/:id/attempts", h.CourseAttempts)
	g.GET("/attempts/:aid", h.GetAttempt)
	g.PUT("/attempts/:aid/answers", h.SaveAnswers)
	g.POST("/attempts/:aid/events", h.LogEvents)
	g.POST("/attempts/:aid/submit", h.SubmitTest)
	g.POST("/attempts/:aid/review", h.ReviewAttempt)
}
